/// A mode contract: the values of a parameter handled as Windows 7 does.
pub type Accepts = fn(u32) -> bool;

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ImplementationLevel {
    Implement,
    State,
    SafeFail,
}

/// Emitted by #[win32]; registration lists only reference this descriptor.
#[derive(Clone, Copy)]
pub struct Api {
    pub module: &'static str,
    pub name: &'static str,
    pub conv: Conv,
    pub handler: Handler,
    pub env_leaf: Option<EnvLeafHandler>,
    pub level: ImplementationLevel,
}

struct Entry {
    host: HostFn,
    level: Option<ImplementationLevel>,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct SignatureConflict {
    pub module: String,
    pub name: String,
    pub registered: Conv,
    pub metadata: Option<Conv>,
}

/// Implementations by (lowercased DLL, case-sensitive export).
/// Legacy registrations coexist with generated adapters and are audited separately.
pub struct Registry {
    fns: HashMap<(String, String), Entry>,
    aliases: HashMap<(String, String), &'static str>,
    signature_conflicts_cache: OnceLock<Vec<SignatureConflict>>,
    data: HashMap<(String, String), Vec<u8>>,
    mode: RunMode,
    replacements: std::collections::BTreeSet<String>,
    /// Mode contracts: the values of a scalar parameter an implementation
    /// handles as Windows 7 does.
    modes: HashMap<(String, String), Vec<(&'static str, Accepts)>>,
    /// Development probe: discovery exposes the whole fixed core catalog.
    expose_fixed_exports: bool,
}

impl Default for Registry {
    fn default() -> Self {
        Self {
            fns: HashMap::new(),
            aliases: HashMap::new(),
            signature_conflicts_cache: OnceLock::new(),
            data: HashMap::new(),
            mode: RunMode::Strict,
            replacements: Default::default(),
            modes: HashMap::new(),
            expose_fixed_exports: std::env::var_os("ADV_PERSONALITY_STRICT")
                .is_some_and(|value| value == "1"),
        }
    }
}

impl Registry {
    /// Exact implemented registrations, including internal COM method names.
    pub fn registered(&self) -> impl Iterator<Item = (&str, &str, HostFn)> {
        self.fns
            .iter()
            .map(|((module, name), entry)| (module.as_str(), name.as_str(), entry.host))
            .chain(self.aliases.iter().filter_map(|((module, name), _)| {
                self.get(module, name)
                    .map(|host| (module.as_str(), name.as_str(), host))
            }))
    }
    /// Register one implementation for both light calls and ordinary traps.
    pub fn add_leaf(&mut self, module: &str, name: &str, conv: Conv, handler: LeafHandler) {
        assert!(
            !adv_machine::thunk::is_audio_binding(module, name),
            "audio bindings cannot be leaf calls"
        );
        self.add(module, name, conv, adv_machine::thunk::leaf_trap);
        self.fns
            .get_mut(&(module.to_ascii_lowercase(), name.to_owned()))
            .expect("just inserted")
            .host
            .leaf = Some(handler);
    }

    /// Full service leaf; None must precede all observable side effects.
    ///
    /// Outcome behaviors cannot opt into the synchronous macro adapter.
    /// ```compile_fail
    /// use adv_abi::{win32, Env, Outcome};
    /// #[win32(kernel32, name = "Sleep", level = implement, leaf)]
    /// fn sleep(_: &mut Env<'_>, _: u32) -> Outcome { Outcome::Return(0) }
    /// ```
    pub fn add_env_leaf(
        &mut self,
        module: &str,
        name: &str,
        conv: Conv,
        ordinary: Handler,
        leaf: EnvLeafHandler,
    ) {
        assert!(
            !adv_machine::thunk::is_audio_binding(module, name),
            "audio bindings cannot be leaf calls"
        );
        self.add(module, name, conv, ordinary);
        self.fns
            .get_mut(&(module.to_ascii_lowercase(), name.to_owned()))
            .expect("just inserted")
            .host
            .env_leaf = Some(leaf);
    }

    /// Opt in only after validating a complete native provider's ABI.
    pub fn replace_module(&mut self, module: &str) {
        self.replacements.insert(module.to_ascii_lowercase());
    }
    pub fn add(&mut self, module: &str, name: &str, conv: Conv, handler: Handler) {
        self.add_with_data(module, name, conv, handler, 0);
    }

    /// Bind immutable, machine-opaque data once rather than resolving per call.
    pub fn add_with_data(
        &mut self,
        module: &str,
        name: &str,
        conv: Conv,
        handler: Handler,
        data: u64,
    ) {
        assert!(
            signature::lookup(module, name).is_none_or(|s| s.data_size.is_none()),
            "a data export cannot be registered as a function: {module}!{name}"
        );
        assert!(
            !self
                .data
                .contains_key(&(module.to_ascii_lowercase(), name.to_owned()))
        );
        self.fns.insert(
            (module.to_ascii_lowercase(), name.to_owned()),
            Entry {
                host: HostFn {
                    leaf: None,
                    env_leaf: None,
                    conv,
                    handler,
                    trace: false,
                    data,
                    guest: None,
                },
                level: None,
            },
        );
        // Every function descriptor insertion/replacement comes through here.
        // Trace, mode, data bytes and replacement policy do not change the
        // registered conventions checked against immutable signature metadata.
        self.signature_conflicts_cache.take();
    }

    /// Register a data cell against the same generated export declarations.
    pub fn register_data(&mut self, module: &str, name: &str, bytes: &[u8]) -> Result<(), String> {
        let key = (module.to_ascii_lowercase(), name.to_owned());
        let size = signature::lookup(module, name)
            .and_then(|s| s.data_size)
            .ok_or_else(|| format!("no generated data declaration: {module}!{name}"))?;
        if bytes.len() != size as usize
            || self.fns.contains_key(&key)
            || self.data.contains_key(&key)
        {
            return Err(format!("conflicting data registration: {module}!{name}"));
        }
        self.data.insert(key, bytes.to_vec());
        Ok(())
    }

    /// Assembly initializes descriptor bytes before synthetic images are built.
    pub fn set_data(&mut self, module: &str, name: &str, bytes: &[u8]) -> Result<(), String> {
        let value = self
            .data
            .get_mut(&(module.to_ascii_lowercase(), name.to_owned()))
            .ok_or_else(|| format!("data export not registered: {module}!{name}"))?;
        if value.len() != bytes.len() {
            return Err(format!("data size mismatch: {module}!{name}"));
        }
        value.copy_from_slice(bytes);
        Ok(())
    }

    pub fn data(&self, module: &str, name: &str) -> Option<&[u8]> {
        let name = self.canonical_name(module, name).unwrap_or(name);
        self.data
            .get(&(module.to_ascii_lowercase(), name.to_owned()))
            .map(Vec::as_slice)
    }

    pub fn register(&mut self, api: Api) {
        self.register_with_data(api, 0);
    }

    /// Preserve immutable binding data when composing typed API decorators.
    pub fn register_with_data(&mut self, api: Api, data: u64) {
        if let Some(leaf) = api.env_leaf {
            self.add_env_leaf(api.module, api.name, api.conv, api.handler, leaf);
            self.fns
                .get_mut(&(api.module.to_ascii_lowercase(), api.name.to_owned()))
                .unwrap()
                .host
                .data = data;
        } else {
            self.add_with_data(api.module, api.name, api.conv, api.handler, data);
        }
        self.fns
            .get_mut(&(api.module.to_ascii_lowercase(), api.name.to_owned()))
            .expect("just inserted")
            .level = Some(api.level);
    }

    /// Bind an SDK-declared name to a direct implementation in the same DLL.
    /// Both names must have the same complete ABI; aliases cannot form chains.
    /// Explicit implementations retain precedence over aliases.
    pub fn register_alias(
        &mut self,
        module: &str,
        name: &str,
        target: &'static str,
    ) -> Result<(), String> {
        self.alias(module, name, target, false)
    }

    /// Declare a same-ABI public code alias when the SDK omits a declaration.
    /// The personality owns that equivalence; both exports must be in the fixed
    /// catalog, and every available SDK declaration is still checked. This does
    /// not infer equivalence from names or permit aliases to another alias.
    pub fn register_export_alias(
        &mut self,
        module: &str,
        name: &str,
        target: &'static str,
    ) -> Result<(), String> {
        self.alias(module, name, target, true)
    }

    fn alias(
        &mut self,
        module: &str,
        name: &str,
        target: &'static str,
        public: bool,
    ) -> Result<(), String> {
        let module = module.to_ascii_lowercase();
        let key = (module.clone(), name.to_owned());
        let valid = signature::lookup(&module, name)
            .zip(signature::lookup(&module, target))
            .map_or_else(
                || {
                    public
                        && [name, target].into_iter().all(|export| {
                            system_exports::lookup(&module, export)
                                .is_some_and(|e| e.kind == system_exports::Kind::Code)
                        })
                        && self
                            .fns
                            .get(&(module.clone(), target.to_owned()))
                            .is_some_and(|entry| {
                                [name, target].into_iter().all(|export| {
                                    signature::lookup(&module, export).is_none_or(|s| {
                                        s.data_size.is_none() && s.conv == Some(entry.host.conv)
                                    })
                                })
                            })
                },
                |(alias, original)| {
                    alias.data_size.is_none()
                        && alias.conv.is_some()
                        && alias.conv == original.conv
                        && alias.return_kind == original.return_kind
                        && alias.return_type == original.return_type
                        && alias.parameters.len() == original.parameters.len()
                        && alias
                            .parameters
                            .iter()
                            .zip(&original.parameters)
                            .all(|(a, b)| {
                                a.kind == b.kind && a.words == b.words && a.type_name == b.type_name
                            })
                        && self
                            .fns
                            .get(&(module.clone(), target.to_owned()))
                            .is_some_and(|entry| Some(entry.host.conv) == original.conv)
                },
            );
        if name == target || !valid || self.data.contains_key(&key) {
            return Err(format!(
                "invalid function alias: {module}!{name} -> {target}"
            ));
        }
        self.aliases.insert(key, target);
        Ok(())
    }

    /// Declare that `module!name` handles `param` as Windows 7 does exactly
    /// for the values `accepts` passes (PERS-EXPORT-10). Other values reach the
    /// implementation unchanged; the declaration lets a survey find them first.
    pub fn accept(&mut self, module: &str, name: &str, param: &'static str, accepts: Accepts) {
        assert!(
            signature::lookup(module, name).is_some_and(|s| s
                .parameters
                .iter()
                .any(|p| p.name == param
                    && p.words == 1
                    && matches!(p.kind, AbiKind::U32 | AbiKind::I32))),
            "a mode contract needs a declared scalar parameter: {module}!{name} {param}"
        );
        let contracts = self
            .modes
            .entry((module.to_ascii_lowercase(), name.to_owned()))
            .or_default();
        contracts.retain(|&(p, _)| p != param);
        contracts.push((param, accepts));
    }

    /// The mode contract of `param` of `module!name`, when one is declared.
    pub fn accepts(&self, module: &str, name: &str, param: &str) -> Option<Accepts> {
        self.modes
            .get(&(module.to_ascii_lowercase(), name.to_owned()))?
            .iter()
            .find(|&&(p, _)| p == param)
            .map(|&(_, accepts)| accepts)
    }

    pub fn add_traced(&mut self, module: &str, name: &str, conv: Conv, handler: Handler) {
        self.add(module, name, conv, handler);
        self.set_trace(module, name, true);
    }

    /// Run `guest` in place of the host trap. The registered handler stays the
    /// implementation of record for the cases the guest code hands over.
    pub fn set_guest(&mut self, module: &str, name: &str, guest: &'static GuestCode) {
        self.fns
            .get_mut(&(module.to_ascii_lowercase(), name.to_owned()))
            .unwrap_or_else(|| panic!("guest code for unregistered {module}!{name}"))
            .host
            .guest = Some(guest);
    }

    /// Attach an audited adapter without replacing ABI metadata or guest code.
    pub fn set_env_leaf(&mut self, module: &str, name: &str, leaf: EnvLeafHandler) {
        assert!(!adv_machine::thunk::is_audio_binding(module, name));
        self.fns
            .get_mut(&(module.to_ascii_lowercase(), name.to_owned()))
            .expect("leaf requires an existing implementation")
            .host
            .env_leaf = Some(leaf);
    }

    pub fn set_trace(&mut self, module: &str, name: &str, on: bool) {
        if let Some(f) = self
            .fns
            .get_mut(&(module.to_ascii_lowercase(), name.to_owned()))
        {
            f.host.trace = on;
        }
    }
    pub fn mode(&self) -> RunMode {
        self.mode
    }
    pub fn set_mode(&mut self, mode: RunMode) {
        self.mode = mode;
    }
    /// ADV_PERSONALITY_STRICT=1 restores whole-catalog discovery for probing
    /// which names a title asks for; calls to missing behavior still fail.
    pub fn set_expose_fixed_exports(&mut self, expose: bool) {
        self.expose_fixed_exports = expose;
    }
    pub fn exposes_fixed_exports(&self) -> bool {
        self.expose_fixed_exports
    }

    pub fn get(&self, module: &str, name: &str) -> Option<HostFn> {
        let canonical = self.canonical_name(module, name);
        let name = canonical.unwrap_or(name);
        if signature::lookup(module, name).is_some_and(|s| s.data_size.is_some()) {
            return None;
        }
        if let Some(entry) = self.registered_entry(module, name) {
            return Some(entry.host);
        }
        let Some(signature) = signature::lookup(module, name) else {
            return matches!(
                system_exports::lookup(module, name)?.kind,
                system_exports::Kind::Code
            )
            .then_some(HostFn {
                leaf: None,
                env_leaf: None,
                // The unknown ABI never returns, so no cleanup is guessed.
                conv: Conv::Cdecl { argc: 0 },
                handler: stub::fixed_dispatch,
                trace: true,
                data: 0,
                guest: None,
            });
        };
        let index = signature::signatures()
            .iter()
            .position(|s| core::ptr::eq(s, signature))
            .expect("signature in table");
        Some(HostFn {
            leaf: None,
            env_leaf: None,
            conv: signature.conv.unwrap_or(Conv::Cdecl { argc: 0 }),
            handler: stub::dispatch,
            trace: true,
            data: index as u64,
            guest: None,
        })
    }

    fn registered_entry(&self, module: &str, name: &str) -> Option<&Entry> {
        let module = module.to_ascii_lowercase();
        self.fns
            .get(&(module.clone(), name.to_owned()))
            .or_else(|| {
                // KernelBase exposes the same public APIs as the registered Win32
                // frontend. Reuse behavior in its own image, without aliasing entry
                // addresses or borrowing the ABI of a differently named function.
                (module == "kernelbase.dll"
                    && system_exports::lookup(&module, name)
                        .is_some_and(|export| export.kind == system_exports::Kind::Code)
                    && system_exports::is_core_export("kernel32.dll", name))
                .then(|| self.fns.get(&("kernel32.dll".to_owned(), name.to_owned())))
                .flatten()
            })
            .or_else(|| {
                // A fixed forwarder shares its target's ABI, so a frontend
                // registered under the forwarding name implements the target.
                system_exports::forwarded_from(&module, name)
                    .iter()
                    .find_map(|(source, alias)| {
                        self.fns.get(&((*source).to_owned(), (*alias).to_owned()))
                    })
            })
    }

    /// An explicit implementation wins over a named or SDK ordinal alias.
    pub fn canonical_name(&self, module: &str, name: &str) -> Option<&'static str> {
        let module = module.to_ascii_lowercase();
        if self.fns.contains_key(&(module.clone(), name.to_owned()))
            || self.data.contains_key(&(module.clone(), name.to_owned()))
        {
            return None;
        }
        self.aliases
            .get(&(module.clone(), name.to_owned()))
            .copied()
            .or_else(|| system_exports::ordinal_name(&module, name))
            .or_else(|| {
                (!system_exports::is_core_module(&module))
                    .then(|| ordinals::lookup(&module, name))
                    .flatten()
            })
    }

    pub fn level(&self, module: &str, name: &str) -> Option<ImplementationLevel> {
        if self.data(module, name).is_some() {
            return Some(ImplementationLevel::State);
        }
        let name = self.canonical_name(module, name).unwrap_or(name);
        self.registered_entry(module, name).and_then(|e| e.level)
    }
    pub fn is_implemented(&self, module: &str, name: &str) -> bool {
        let name = self.canonical_name(module, name).unwrap_or(name);
        self.registered_entry(module, name).is_some() || self.data(module, name).is_some()
    }

    /// The personality class of a declared export, or None for a name the
    /// personality never declares. Fixed forwarders are classified by their
    /// final target; a frontend under either name implements both.
    pub fn classify(&self, module: &str, name: &str) -> Option<ExportClass> {
        let name = self.canonical_name(module, name).unwrap_or(name);
        let (target, target_name) = if system_exports::has_module(module) {
            let export = system_exports::lookup(module, name)?;
            if export.kind == system_exports::Kind::DataUnsupported {
                return Some(if self.data(module, name).is_some() {
                    ExportClass::Implemented
                } else {
                    ExportClass::DataUnsupported
                });
            }
            system_exports::final_target(module, export.name).unwrap_or((module, name))
        } else {
            (module, name)
        };
        if self.is_implemented(module, name) || self.is_implemented(target, target_name) {
            Some(ExportClass::Implemented)
        } else if personality::is_reviewed(module, name)
            || personality::is_reviewed(target, target_name)
        {
            Some(ExportClass::Reviewed)
        } else if system_exports::has_module(module) || signature::lookup(module, name).is_some() {
            Some(ExportClass::Hidden)
        } else {
            None
        }
    }

    /// Discovery exposes only callable capability, so a title's own fallback
    /// for an older Windows still runs. ADV_PERSONALITY_STRICT=1 additionally
    /// exposes hidden fixed core names.
    pub fn dynamic_available(&self, module: &str, name: &str) -> bool {
        match self.classify(module, name) {
            Some(class) if class.discoverable() => true,
            Some(ExportClass::Hidden) => {
                self.expose_fixed_exports && system_exports::has_module(module)
            }
            _ => false,
        }
    }
    pub fn len(&self) -> usize {
        self.fns.len() + self.data.len()
    }
    pub fn is_empty(&self) -> bool {
        self.fns.is_empty() && self.data.is_empty()
    }

    /// Include generated DLLs so static imports retain diagnostic stub bindings.
    pub fn has_module(&self, module: &str) -> bool {
        let module = module.to_ascii_lowercase();
        system_exports::has_module(&module)
            || self.fns.keys().any(|(m, _)| *m == module)
            || self.data.keys().any(|(m, _)| *m == module)
            || signature::signatures().iter().any(|s| s.module == module)
    }

    /// Names for the synthetic PE export writer, with implementations and stubs together.
    pub fn exports(&self, module: &str) -> Vec<String> {
        let module = module.to_ascii_lowercase();
        if system_exports::has_module(&module) {
            return system_exports::exports(&module)
                .map(|export| export.name.to_owned())
                .collect();
        }
        let mut names: Vec<_> = signature::signatures()
            .iter()
            .filter(|s| s.module == module)
            .map(|s| s.name.to_owned())
            .collect();
        names.extend(
            self.fns
                .keys()
                .filter(|(m, name)| *m == module && !name.contains("::"))
                .map(|(_, n)| n.clone()),
        );
        names.extend(
            self.data
                .keys()
                .filter(|(m, _)| *m == module)
                .map(|(_, name)| name.clone()),
        );
        names.sort();
        names.dedup();
        names
    }

    pub fn signature_conflicts(&self) -> Vec<SignatureConflict> {
        self.signature_conflicts_cache
            .get_or_init(|| self.scan_signature_conflicts())
            .clone()
    }

    fn scan_signature_conflicts(&self) -> Vec<SignatureConflict> {
        let mut conflicts = Vec::new();
        for ((module, name), entry) in &self.fns {
            let metadata = if let Some((interface, method)) = name.split_once("::") {
                signature::lookup_com(interface, method)
            } else {
                signature::lookup(module, name)
            };
            if let Some(metadata) = metadata
                && metadata.conv != Some(entry.host.conv)
            {
                conflicts.push(SignatureConflict {
                    module: module.clone(),
                    name: name.clone(),
                    registered: entry.host.conv,
                    metadata: metadata.conv,
                });
            }
        }
        conflicts.sort_by(|a, b| (&a.module, &a.name).cmp(&(&b.module, &b.name)));
        conflicts
    }

    /// APIs whose legacy hand-written signature has no authoritative metadata entry.
    pub fn missing_signatures(&self) -> Vec<String> {
        let mut missing: Vec<_> = self
            .fns
            .keys()
            .filter(|(module, name)| {
                if let Some((interface, method)) = name.split_once("::") {
                    signature::lookup_com(interface, method).is_none()
                } else {
                    signature::lookup(module, name).is_none()
                }
            })
            .map(|(module, name)| format!("{module}!{name}"))
            .collect();
        missing.sort();
        missing
    }

    pub fn coverage(&self) -> Coverage {
        let mut coverage = Coverage {
            generated_exports: signature::signatures().len(),
            ..Coverage::default()
        };
        for entry in self.fns.values() {
            match entry.level {
                Some(ImplementationLevel::Implement) => coverage.implement += 1,
                Some(ImplementationLevel::State) => coverage.state += 1,
                Some(ImplementationLevel::SafeFail) => coverage.safe_fail += 1,
                None => coverage.legacy += 1,
            }
        }
        coverage.state += self.data.len();
        coverage
    }
}

