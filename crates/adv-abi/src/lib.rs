#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ImplementationLevel {
    Implement,
    State,
    SafeFail,
}

/// Emitted by #[win32]; registration lists only reference this descriptor.
#[derive(Clone, Copy)]
pub struct Api {
    pub module: &'static str,
    pub name: &'static str,
    pub conv: Conv,
    pub handler: Handler,
    pub level: ImplementationLevel,
}

struct Entry {
    host: HostFn,
    level: Option<ImplementationLevel>,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct SignatureConflict {
    pub module: String,
    pub name: String,
    pub registered: Conv,
    pub metadata: Option<Conv>,
}

/// Implementations by (lowercased DLL, case-sensitive export).
/// Legacy registrations coexist with generated adapters and are audited separately.
pub struct Registry {
    fns: HashMap<(String, String), Entry>,
    aliases: HashMap<(String, String), &'static str>,
    signature_conflicts_cache: OnceLock<Vec<SignatureConflict>>,
    data: HashMap<(String, String), Vec<u8>>,
    mode: RunMode,
    replacements: std::collections::BTreeSet<String>,
}

impl Default for Registry {
    fn default() -> Self {
        Self {
            fns: HashMap::new(),
            aliases: HashMap::new(),
            signature_conflicts_cache: OnceLock::new(),
            data: HashMap::new(),
            mode: RunMode::Strict,
            replacements: Default::default(),
        }
    }
}

impl Registry {
    /// Opt in only after validating a complete native provider's ABI.
    pub fn replace_module(&mut self, module: &str) {
        self.replacements.insert(module.to_ascii_lowercase());
    }
    pub fn add(&mut self, module: &str, name: &str, conv: Conv, handler: Handler) {
        self.add_with_data(module, name, conv, handler, 0);
    }

    /// Bind immutable, machine-opaque data once rather than resolving per call.
    pub fn add_with_data(
        &mut self,
        module: &str,
        name: &str,
        conv: Conv,
        handler: Handler,
        data: u64,
    ) {
        assert!(
            signature::lookup(module, name).is_none_or(|s| s.data_size.is_none()),
            "a data export cannot be registered as a function: {module}!{name}"
        );
        assert!(
            !self
                .data
                .contains_key(&(module.to_ascii_lowercase(), name.to_owned()))
        );
        self.fns.insert(
            (module.to_ascii_lowercase(), name.to_owned()),
            Entry {
                host: HostFn {
                    conv,
                    handler,
                    trace: false,
                    data,
                    guest: None,
                },
                level: None,
            },
        );
        // Every function descriptor insertion/replacement comes through here.
        // Trace, mode, data bytes and replacement policy do not change the
        // registered conventions checked against immutable signature metadata.
        self.signature_conflicts_cache.take();
    }

    /// Register a data cell against the same generated export declarations.
    pub fn register_data(&mut self, module: &str, name: &str, bytes: &[u8]) -> Result<(), String> {
        let key = (module.to_ascii_lowercase(), name.to_owned());
        let size = signature::lookup(module, name)
            .and_then(|s| s.data_size)
            .ok_or_else(|| format!("no generated data declaration: {module}!{name}"))?;
        if bytes.len() != size as usize
            || self.fns.contains_key(&key)
            || self.data.contains_key(&key)
        {
            return Err(format!("conflicting data registration: {module}!{name}"));
        }
        self.data.insert(key, bytes.to_vec());
        Ok(())
    }

    /// Assembly initializes descriptor bytes before synthetic images are built.
    pub fn set_data(&mut self, module: &str, name: &str, bytes: &[u8]) -> Result<(), String> {
        let value = self
            .data
            .get_mut(&(module.to_ascii_lowercase(), name.to_owned()))
            .ok_or_else(|| format!("data export not registered: {module}!{name}"))?;
        if value.len() != bytes.len() {
            return Err(format!("data size mismatch: {module}!{name}"));
        }
        value.copy_from_slice(bytes);
        Ok(())
    }

    pub fn data(&self, module: &str, name: &str) -> Option<&[u8]> {
        let name = self.canonical_name(module, name).unwrap_or(name);
        self.data
            .get(&(module.to_ascii_lowercase(), name.to_owned()))
            .map(Vec::as_slice)
    }

    pub fn register(&mut self, api: Api) {
        self.register_with_data(api, 0);
    }

    /// Preserve immutable binding data when composing typed API decorators.
    pub fn register_with_data(&mut self, api: Api, data: u64) {
        self.add_with_data(api.module, api.name, api.conv, api.handler, data);
        self.fns
            .get_mut(&(api.module.to_ascii_lowercase(), api.name.to_owned()))
            .expect("just inserted")
            .level = Some(api.level);
    }

    /// Bind an SDK-declared name to a direct implementation in the same DLL.
    /// Both names must have the same complete ABI; aliases cannot form chains.
    /// Explicit implementations retain precedence over aliases.
    pub fn register_alias(
        &mut self,
        module: &str,
        name: &str,
        target: &'static str,
    ) -> Result<(), String> {
        let module = module.to_ascii_lowercase();
        let key = (module.clone(), name.to_owned());
        let valid = signature::lookup(&module, name)
            .zip(signature::lookup(&module, target))
            .is_some_and(|(alias, original)| {
                alias.data_size.is_none()
                    && alias.conv.is_some()
                    && alias.conv == original.conv
                    && alias.return_kind == original.return_kind
                    && alias.return_type == original.return_type
                    && alias.parameters.len() == original.parameters.len()
                    && alias
                        .parameters
                        .iter()
                        .zip(&original.parameters)
                        .all(|(a, b)| {
                            a.kind == b.kind && a.words == b.words && a.type_name == b.type_name
                        })
                    && self
                        .fns
                        .get(&(module.clone(), target.to_owned()))
                        .is_some_and(|entry| Some(entry.host.conv) == original.conv)
            });
        if name == target || !valid || self.data.contains_key(&key) {
            return Err(format!(
                "invalid function alias: {module}!{name} -> {target}"
            ));
        }
        self.aliases.insert(key, target);
        Ok(())
    }

    pub fn add_traced(&mut self, module: &str, name: &str, conv: Conv, handler: Handler) {
        self.add(module, name, conv, handler);
        self.set_trace(module, name, true);
    }

    /// Run `guest` in place of the host trap. The registered handler stays the
    /// implementation of record for the cases the guest code hands over.
    pub fn set_guest(&mut self, module: &str, name: &str, guest: &'static GuestCode) {
        self.fns
            .get_mut(&(module.to_ascii_lowercase(), name.to_owned()))
            .unwrap_or_else(|| panic!("guest code for unregistered {module}!{name}"))
            .host
            .guest = Some(guest);
    }

    pub fn set_trace(&mut self, module: &str, name: &str, on: bool) {
        if let Some(f) = self
            .fns
            .get_mut(&(module.to_ascii_lowercase(), name.to_owned()))
        {
            f.host.trace = on;
        }
    }
    pub fn mode(&self) -> RunMode {
        self.mode
    }
    pub fn set_mode(&mut self, mode: RunMode) {
        self.mode = mode;
    }

    pub fn get(&self, module: &str, name: &str) -> Option<HostFn> {
        let canonical = self.canonical_name(module, name);
        let name = canonical.unwrap_or(name);
        if signature::lookup(module, name).is_some_and(|s| s.data_size.is_some()) {
            return None;
        }
        if let Some(entry) = self
            .fns
            .get(&(module.to_ascii_lowercase(), name.to_owned()))
        {
            return Some(entry.host);
        }
        let signature = signature::lookup(module, name)?;
        let index = signature::signatures()
            .iter()
            .position(|s| core::ptr::eq(s, signature))
            .expect("signature in table");
        Some(HostFn {
            conv: signature.conv.unwrap_or(Conv::Cdecl { argc: 0 }),
            handler: stub::dispatch,
            trace: true,
            data: index as u64,
            guest: None,
        })
    }

    /// An explicit implementation wins over a named or SDK ordinal alias.
    pub fn canonical_name(&self, module: &str, name: &str) -> Option<&'static str> {
        let module = module.to_ascii_lowercase();
        if self.fns.contains_key(&(module.clone(), name.to_owned()))
            || self.data.contains_key(&(module.clone(), name.to_owned()))
        {
            return None;
        }
        self.aliases
            .get(&(module.clone(), name.to_owned()))
            .copied()
            .or_else(|| ordinals::lookup(&module, name))
    }

    pub fn level(&self, module: &str, name: &str) -> Option<ImplementationLevel> {
        if self.data(module, name).is_some() {
            return Some(ImplementationLevel::State);
        }
        let name = self.canonical_name(module, name).unwrap_or(name);
        self.fns
            .get(&(module.to_ascii_lowercase(), name.to_owned()))
            .and_then(|e| e.level)
    }
    pub fn is_implemented(&self, module: &str, name: &str) -> bool {
        let name = self.canonical_name(module, name).unwrap_or(name);
        self.fns
            .contains_key(&(module.to_ascii_lowercase(), name.to_owned()))
            || self.data(module, name).is_some()
    }

    /// Dynamic capability probes expose registered behavior, including explicit
    /// safe failures. Signature metadata alone does not promise an API exists.
    /// Reviewed proxy exports remain discoverable without becoming implemented.
    pub fn dynamic_available(&self, module: &str, name: &str) -> bool {
        let name = self.canonical_name(module, name).unwrap_or(name);
        self.is_implemented(module, name)
            || include_str!("../../../data/abi/dynamic_exports.tsv")
                .lines()
                .filter(|line| !line.is_empty() && !line.starts_with('#'))
                .any(|line| {
                    let mut fields = line.split('\t');
                    fields
                        .next()
                        .is_some_and(|dll| dll.eq_ignore_ascii_case(module))
                        && fields.next() == Some(name)
                })
    }
    pub fn len(&self) -> usize {
        self.fns.len() + self.data.len()
    }
    pub fn is_empty(&self) -> bool {
        self.fns.is_empty() && self.data.is_empty()
    }

    /// Include generated DLLs so static imports retain diagnostic stub bindings.
    pub fn has_module(&self, module: &str) -> bool {
        let module = module.to_ascii_lowercase();
        self.fns.keys().any(|(m, _)| *m == module)
            || self.data.keys().any(|(m, _)| *m == module)
            || signature::signatures().iter().any(|s| s.module == module)
    }

    /// Names for the synthetic PE export writer, with implementations and stubs together.
    pub fn exports(&self, module: &str) -> Vec<String> {
        let module = module.to_ascii_lowercase();
        let mut names: Vec<_> = signature::signatures()
            .iter()
            .filter(|s| s.module == module)
            .map(|s| s.name.to_owned())
            .collect();
        names.extend(
            self.fns
                .keys()
                .filter(|(m, name)| *m == module && !name.contains("::"))
                .map(|(_, n)| n.clone()),
        );
        names.extend(
            self.data
                .keys()
                .filter(|(m, _)| *m == module)
                .map(|(_, name)| name.clone()),
        );
        names.sort();
        names.dedup();
        names
    }

    pub fn signature_conflicts(&self) -> Vec<SignatureConflict> {
        self.signature_conflicts_cache
            .get_or_init(|| self.scan_signature_conflicts())
            .clone()
    }

    fn scan_signature_conflicts(&self) -> Vec<SignatureConflict> {
        let mut conflicts = Vec::new();
        for ((module, name), entry) in &self.fns {
            let metadata = if let Some((interface, method)) = name.split_once("::") {
                signature::lookup_com(interface, method)
            } else {
                signature::lookup(module, name)
            };
            if let Some(metadata) = metadata {
                if metadata.conv != Some(entry.host.conv) {
                    conflicts.push(SignatureConflict {
                        module: module.clone(),
                        name: name.clone(),
                        registered: entry.host.conv,
                        metadata: metadata.conv,
                    });
                }
            }
        }
        conflicts.sort_by(|a, b| (&a.module, &a.name).cmp(&(&b.module, &b.name)));
        conflicts
    }

    /// APIs whose legacy hand-written signature has no authoritative metadata entry.
    pub fn missing_signatures(&self) -> Vec<String> {
        let mut missing: Vec<_> = self
            .fns
            .keys()
            .filter(|(module, name)| {
                if let Some((interface, method)) = name.split_once("::") {
                    signature::lookup_com(interface, method).is_none()
                } else {
                    signature::lookup(module, name).is_none()
                }
            })
            .map(|(module, name)| format!("{module}!{name}"))
            .collect();
        missing.sort();
        missing
    }

    pub fn coverage(&self) -> Coverage {
        let mut coverage = Coverage {
            generated_exports: signature::signatures().len(),
            ..Coverage::default()
        };
        for entry in self.fns.values() {
            match entry.level {
                Some(ImplementationLevel::Implement) => coverage.implement += 1,
                Some(ImplementationLevel::State) => coverage.state += 1,
                Some(ImplementationLevel::SafeFail) => coverage.safe_fail += 1,
                None => coverage.legacy += 1,
            }
        }
        coverage.state += self.data.len();
        coverage
    }
}

#[cfg(test)]
mod signature_conflict_cache_tests {
    use super::*;

    fn file_pointer_api(conv: Conv) -> Api {
        Api {
            module: "kernel32.dll",
            name: "SetFilePointerEx",
            conv,
            handler: |_| Outcome::Return(0),
            level: ImplementationLevel::Implement,
        }
    }

    #[test]
    fn function_registration_replacements_invalidate_cached_conflicts() {
        let mut registry = Registry::default();
        assert!(registry.signature_conflicts().is_empty());
        assert!(registry.signature_conflicts_cache.get().is_some());
        registry.add_traced(
            "KERNEL32.DLL",
            "SetFilePointerEx",
            Conv::Stdcall { argc: 4 },
            |_| Outcome::Return(0),
        );
        assert!(registry.signature_conflicts_cache.get().is_none());
        assert_eq!(registry.signature_conflicts().len(), 1);
        registry.register_with_data(file_pointer_api(Conv::Stdcall { argc: 5 }), 17);
        assert!(registry.signature_conflicts_cache.get().is_none());
        assert!(registry.signature_conflicts().is_empty());
        registry.add_with_data(
            "kernel32.dll",
            "SetFilePointerEx",
            Conv::Stdcall { argc: 4 },
            |_| Outcome::Return(0),
            23,
        );
        assert_eq!(registry.signature_conflicts().len(), 1);
        registry.register(file_pointer_api(Conv::Stdcall { argc: 5 }));
        assert!(registry.signature_conflicts().is_empty());
    }

    #[test]
    fn cached_com_and_dll_conflicts_remain_sorted_and_independently_owned() {
        let mut registry = Registry::default();
        registry.add(
            "z.dll",
            "IDirect3DDevice9::Present",
            Conv::Stdcall { argc: 4 },
            |_| Outcome::Return(0),
        );
        registry.register(file_pointer_api(Conv::Stdcall { argc: 4 }));
        let expected = vec![
            SignatureConflict {
                module: "kernel32.dll".into(),
                name: "SetFilePointerEx".into(),
                registered: Conv::Stdcall { argc: 4 },
                metadata: Some(Conv::Stdcall { argc: 5 }),
            },
            SignatureConflict {
                module: "z.dll".into(),
                name: "IDirect3DDevice9::Present".into(),
                registered: Conv::Stdcall { argc: 4 },
                metadata: Some(Conv::Stdcall { argc: 5 }),
            },
        ];
        assert_eq!(registry.signature_conflicts(), expected);
        let mut returned = registry.signature_conflicts();
        returned[0].name.clear();
        assert_eq!(registry.signature_conflicts(), expected);
        registry.add(
            "z.dll",
            "IDirect3DDevice9::Present",
            Conv::Stdcall { argc: 5 },
            |_| Outcome::Return(0),
        );
        assert_eq!(registry.signature_conflicts(), expected[..1]);
    }

    #[test]
    fn unrelated_registry_mutations_preserve_cached_signature_diagnostics() {
        let mut registry = Registry::default();
        registry.register(file_pointer_api(Conv::Stdcall { argc: 4 }));
        let expected = registry.signature_conflicts();
        registry.set_trace("kernel32.dll", "SetFilePointerEx", true);
        registry.set_mode(RunMode::Discovery);
        registry.replace_module("kernel32.dll");
        registry
            .register_data("msvcr90.dll", "_acmdln", &[0; 4])
            .unwrap();
        registry
            .set_data("msvcr90.dll", "_acmdln", &17u32.to_le_bytes())
            .unwrap();
        assert!(registry.signature_conflicts_cache.get().is_some());
        assert_eq!(registry.signature_conflicts(), expected);
    }
}

#[cfg(test)]
mod named_alias_tests {
    use super::*;

    fn registry() -> Registry {
        let mut registry = Registry::default();
        registry.register_with_data(
            Api {
                module: "kernel32.dll",
                name: "lstrcpyA",
                conv: Conv::Stdcall { argc: 2 },
                handler: |_| Outcome::Return(0),
                level: ImplementationLevel::Implement,
            },
            17,
        );
        registry
    }

    #[test]
    fn named_alias_uses_live_target_and_preserves_export_case() {
        let mut registry = registry();
        registry
            .register_alias("KERNEL32.DLL", "lstrcpy", "lstrcpyA")
            .unwrap();
        assert_eq!(
            registry.canonical_name("kernel32.dll", "lstrcpy"),
            Some("lstrcpyA")
        );
        assert!(registry.is_implemented("kernel32.dll", "lstrcpy"));
        assert!(registry.dynamic_available("kernel32.dll", "lstrcpy"));
        assert_eq!(
            registry.level("kernel32.dll", "lstrcpy"),
            Some(ImplementationLevel::Implement)
        );
        assert_eq!(registry.get("kernel32.dll", "lstrcpy").unwrap().data, 17);
        registry.set_trace("kernel32.dll", "lstrcpyA", true);
        assert!(registry.get("kernel32.dll", "lstrcpy").unwrap().trace);
        assert!(!registry.is_implemented("kernel32.dll", "LSTRCPY"));
        assert!(
            registry
                .exports("kernel32.dll")
                .iter()
                .any(|name| name == "lstrcpy")
        );
        assert!(registry.signature_conflicts().is_empty());
    }

    #[test]
    fn explicit_alias_implementation_takes_precedence() {
        let mut registry = registry();
        registry
            .register_alias("kernel32.dll", "lstrcpy", "lstrcpyA")
            .unwrap();
        registry.add_with_data(
            "kernel32.dll",
            "lstrcpy",
            Conv::Stdcall { argc: 2 },
            |_| Outcome::Return(0),
            29,
        );
        assert_eq!(registry.canonical_name("kernel32.dll", "lstrcpy"), None);
        assert_eq!(registry.get("kernel32.dll", "lstrcpy").unwrap().data, 29);
    }

    #[test]
    fn undeclared_different_encoding_missing_target_and_cycles_are_rejected() {
        let mut registry = registry();
        assert!(
            registry
                .register_alias("kernel32.dll", "unknown", "lstrcpyA")
                .is_err()
        );
        assert!(
            registry
                .register_alias("kernel32.dll", "lstrcpyW", "lstrcpyA")
                .is_err()
        );
        assert!(
            registry
                .register_alias("kernel32.dll", "lstrcpy", "lstrcpy")
                .is_err()
        );
        assert!(
            registry
                .register_alias("kernel32.dll", "lstrcpy", "lstrcpyW")
                .is_err()
        );
        registry
            .register_alias("kernel32.dll", "lstrcpy", "lstrcpyA")
            .unwrap();
        assert!(
            registry
                .register_alias("kernel32.dll", "lstrcpyA", "lstrcpy")
                .is_err()
        );
    }
}

#[derive(Debug, Default, PartialEq, Eq)]
pub struct Coverage {
    pub generated_exports: usize,
    pub implement: usize,
    pub state: usize,
    pub safe_fail: usize,
    pub legacy: usize,
}

impl adv_machine::Resolver for Registry {
    fn host_data(&self, module: &str, name: &str) -> Option<&[u8]> {
        self.data(module, name)
    }
    fn data_size(&self, module: &str, name: &str) -> Option<u32> {
        let name = self.canonical_name(module, name).unwrap_or(name);
        signature::lookup(module, name).and_then(|s| s.data_size)
    }
    fn replaces_module(&self, module: &str) -> bool {
        self.replacements.contains(&module.to_ascii_lowercase())
    }
    fn canonical_name(&self, module: &str, name: &str) -> Option<String> {
        Registry::canonical_name(self, module, name).map(str::to_owned)
    }
    fn host_fn(&self, module: &str, name: &str) -> Option<HostFn> {
        self.get(module, name)
    }
    fn provides(&self, module: &str) -> bool {
        self.has_module(module)
    }
    fn implemented(&self, module: &str, name: &str) -> bool {
        self.is_implemented(module, name)
    }
}
