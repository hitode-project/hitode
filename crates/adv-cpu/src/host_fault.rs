    struct Code {
        module: Option<JITModule>,
        unwind: Vec<UnwindRegistration>,
        entry: usize,
        body: usize,
        len: usize,
        site: FaultSite,
        destroyed: Arc<AtomicBool>,
    }
    impl Drop for Code {
        fn drop(&mut self) {
            // SAFETY: all CodeRegion borrows and native calls have ended.
            self.unwind.clear();
            unsafe { self.module.take().unwrap().free_memory() };
            self.destroyed.store(true, Ordering::Release);
        }
    }
    fn code(access: Access, linked: bool, wide: bool) -> Code {
        let mut module = JITModule::new(
            JITBuilder::with_flags(
                &[("preserve_frame_pointers", "true"), ("unwind_info", "true")],
                default_libcall_names(),
            )
            .unwrap(),
        );
        let mut recipes = Vec::new();
        let ptr = module.target_config().pointer_type();
        let mut signature = module.make_signature();
        if linked {
            signature.call_conv = cranelift_codegen::isa::CallConv::Tail;
        }
        signature.params.extend([AbiParam::new(ptr); 2]);
        signature.returns.push(AbiParam::new(types::I32));
        let id = module
            .declare_function("fault_body", Linkage::Local, &signature)
            .unwrap();
        let mut context = module.make_context();
        context.func.signature = signature.clone();
        let mut fb_context = FunctionBuilderContext::new();
        {
            let mut b = FunctionBuilder::new(&mut context.func, &mut fb_context);
            let entry = b.create_block();
            let body = b.create_block();
            let recovery = b.create_block();
            b.append_block_params_for_function_params(entry);
            b.switch_to_block(entry);
            let state = b.block_params(entry)[0];
            let memory = b.block_params(entry)[1];
            // Keep a real same-frame epilogue reachable to the optimizer. The
            // normal state does not take this branch; the VEH targets it by PC.
            let flags = b.ins().load(
                types::I32,
                MemFlags::trusted(),
                state,
                offset_of!(CpuState, eflags) as i32,
            );
            let recover =
                b.ins()
                    .icmp_imm(cranelift_codegen::ir::condcodes::IntCC::Equal, flags, -1);
            b.ins().brif(recover, recovery, &[], body, &[]);
            b.switch_to_block(body);
            let changed = b.ins().iconst(types::I32, 0xdeadbeef);
            b.ins().store(MemFlags::trusted(), changed, state, 0);
            b.ins().store(
                MemFlags::trusted(),
                changed,
                state,
                offset_of!(CpuState, eflags) as i32,
            );
            b.set_srcloc(SourceLoc::new(1));
            if access == Access::Read {
                let value = b.ins().load(types::I32, MemFlags::new(), memory, 0);
                b.ins().return_(&[value]);
            } else {
                if wide {
                    let byte = b.ins().iconst(types::I8, 0xa5);
                    let value = b.ins().splat(types::I8X16, byte);
                    b.ins().store(MemFlags::new(), value, memory, 0);
                } else {
                    b.ins().store(MemFlags::new(), changed, memory, 0);
                }
                let value = b.ins().iconst(types::I32, 0);
                b.ins().return_(&[value]);
            }
            b.switch_to_block(recovery);
            b.set_srcloc(SourceLoc::new(2));
            let result = b
                .ins()
                .iconst(types::I32, if access == Access::Read { 3 } else { 4 });
            b.ins().return_(&[result]);
            b.seal_all_blocks();
            b.finalize();
        }
        module.define_function(id, &mut context).unwrap();
        let compiled = context.compiled_code().unwrap();
        let fault = compiled
            .buffer
            .traps()
            .iter()
            .find(|t| t.code == cranelift_codegen::ir::TrapCode::HEAP_OUT_OF_BOUNDS)
            .unwrap()
            .offset as usize;
        let recovery = compiled
            .buffer
            .get_srclocs_sorted()
            .iter()
            .find(|s| s.loc == SourceLoc::new(2))
            .unwrap()
            .start as usize;
        let len = compiled.code_buffer().len();
        recipes.push((
            id,
            len,
            compiled.create_unwind_info(module.isa()).unwrap().unwrap(),
        ));
        let inner = if linked {
            let tail = module
                .declare_function("linked_region", Linkage::Local, &signature)
                .unwrap();
            let mut caller = module.make_context();
            caller.func.signature = signature;
            let callee = module.declare_func_in_func(id, &mut caller.func);
            {
                let mut b = FunctionBuilder::new(&mut caller.func, &mut fb_context);
                let entry = b.create_block();
                b.append_block_params_for_function_params(entry);
                b.switch_to_block(entry);
                let args = b.block_params(entry).to_vec();
                b.ins().return_call(callee, &args);
                b.seal_all_blocks();
                b.finalize();
            }
            module.define_function(tail, &mut caller).unwrap();
            let compiled = caller.compiled_code().unwrap();
            recipes.push((
                tail,
                compiled.code_buffer().len(),
                compiled.create_unwind_info(module.isa()).unwrap().unwrap(),
            ));
            tail
        } else {
            id
        };
        let entry_id = if linked {
            let mut wrapper = module.make_context();
            wrapper.func.signature = module.make_signature();
            wrapper
                .func
                .signature
                .params
                .extend([AbiParam::new(ptr); 2]);
            wrapper
                .func
                .signature
                .returns
                .push(AbiParam::new(types::I32));
            let entry_id = module
                .declare_function("native_entry", Linkage::Local, &wrapper.func.signature)
                .unwrap();
            let callee = module.declare_func_in_func(inner, &mut wrapper.func);
            {
                let mut b = FunctionBuilder::new(&mut wrapper.func, &mut fb_context);
                let entry = b.create_block();
                b.append_block_params_for_function_params(entry);
                b.switch_to_block(entry);
                let args = b.block_params(entry).to_vec();
                let call = b.ins().call(callee, &args);
                let result = b.inst_results(call)[0];
                b.ins().return_(&[result]);
                b.seal_all_blocks();
                b.finalize();
            }
            module.define_function(entry_id, &mut wrapper).unwrap();
            let compiled = wrapper.compiled_code().unwrap();
            recipes.push((
                entry_id,
                compiled.code_buffer().len(),
                compiled.create_unwind_info(module.isa()).unwrap().unwrap(),
            ));
            entry_id
        } else {
            id
        };
        module.finalize_definitions().unwrap();
        let body = module.get_finalized_function(id) as usize;
        let unwind = recipes
            .into_iter()
            .filter_map(|(id, len, recipe)| {
                let cranelift_codegen::isa::unwind::UnwindInfo::WindowsX64(info) = recipe else {
                    panic!("Windows x64 unwind required")
                };
                let registration = unsafe {
                    UnwindRegistration::new(module.get_finalized_function(id) as usize, len, &info)
                };
                if (linked && id == entry_id) || wide {
                    assert!(
                        registration.is_err(),
                        "clobber save recipes must stay unsupported"
                    );
                    None
                } else {
                    Some(registration.unwrap())
                }
            })
            .collect();
        Code {
            entry: module.get_finalized_function(entry_id) as usize,
            body,
            len,
            site: FaultSite {
                host_pc: body + fault,
                recovery_pc: body + recovery,
                guest_pc: PC,
                width: if wide { 16 } else { 4 },
                access,
            },
            module: Some(module),
            unwind,
            destroyed: Arc::new(AtomicBool::new(false)),
        }
    }
    fn initial() -> CpuState {
        let mut state = CpuState {
            eip: PC,
            regs: [0x12345678; 8],
            eflags: 0x246,
            xmm: [[0x91; 16]; 8],
            mmx: [0x123456789abcdef; 8],
            mmx_mode: 0x103,
            fuel: 57,
            ..CpuState::default()
        };
        state
            .x87
            .push(crate::X87Register::from_parts(0x8000000000000000, 0x3fff));
        state
    }
    fn region<'a>(code: &'a Code, sites: &'a [FaultSite]) -> CodeRegion<'a> {
        // SAFETY: this helper borrows the owning JIT module; sites and cold
        // epilogue offsets are obtained from that exact finalized compilation.
        unsafe { CodeRegion::new(code, code.body, code.len, sites) }.unwrap()
    }
    fn probe(code: &Code, state: *mut CpuState, memory: *mut u8) -> ProbeResult {
        let mut result = ProbeResult::default();
        // SAFETY: native code is finalized and borrowed alive. Unknown faults
        // are caught in the C boundary below the calling Rust test frame.
        unsafe {
            adv_host_fault_probe(
                code.entry as *const c_void,
                state.cast(),
                memory.cast(),
                &mut result,
            )
        };
        result
    }

    #[test]
    fn real_read_and_write_faults_restore_full_guest_state_and_return_normally() {
        for access in [Access::Read, Access::Write] {
            let memory = Reservation::new(8192).unwrap();
            memory.commit(0, 8192).unwrap();
            let code = code(access, false, false);
            let sites = [code.site];
            let regions = [region(&code, &sites)];
            let mut state = initial();
            let mut expected = state.clone();
            expected.fault_addr = DATA;
            let checkpoint = Checkpoint::new(state.clone(), DATA);
            let scope = unsafe {
                memory.temporary_protection(
                    0,
                    4096,
                    if access == Access::Read {
                        HostProtection::NoAccess
                    } else {
                        HostProtection::Read
                    },
                )
            }
            .unwrap();
            let (result, handled) =
                with_session(&mut state, &checkpoint, &regions, &memory, DATA, |state| {
                    probe(&code, state, memory.ptr.as_ptr())
                })
                .unwrap();
            assert_eq!(result.exception, 0);
            assert_eq!(result.result, if access == Access::Read { 3 } else { 4 });
            assert_eq!(handled, 1);
            assert_eq!(state, expected);
            drop(scope);
            assert_eq!(unsafe { *memory.ptr.as_ptr().cast::<u32>() }, 0);
        }
    }

    #[test]
    fn unknown_pc_address_access_or_stale_recipe_falls_through_to_c_seh() {
        let memory = Reservation::new(8192).unwrap();
        memory.commit(0, 8192).unwrap();
        let code = code(Access::Read, false, false);
        let scope =
            unsafe { memory.temporary_protection(0, 8192, HostProtection::NoAccess) }.unwrap();
        for case in 0..4 {
            let mut site = code.site;
            if case == 0 {
                site.host_pc += 1;
            }
            if case == 2 {
                site.access = Access::Write;
            }
            let sites = [site];
            let regions = [region(&code, &sites)];
            let mut state = initial();
            let mut before = state.clone();
            if case == 3 {
                before.eip += 1;
            }
            let checkpoint = Checkpoint::new(before, DATA);
            let address = if case == 1 {
                unsafe { memory.ptr.as_ptr().add(4096) }
            } else {
                memory.ptr.as_ptr()
            };
            let (result, handled) =
                with_session(&mut state, &checkpoint, &regions, &memory, DATA, |state| {
                    probe(&code, state, address)
                })
                .unwrap();
            assert_eq!(result.exception, ACCESS_VIOLATION);
            assert_eq!(result.pc, code.site.host_pc);
            assert_eq!(handled, 0);
            // The native stores happened before the fault. An unrelated fault
            // must not be turned into a guest rollback by our handler.
            assert_eq!(state.regs[0], 0xdeadbeef);
            assert_eq!(state.eflags, 0xdeadbeef);
        }
        drop(scope);
    }

    #[test]
    fn tail_linked_fault_keeps_code_alive_and_does_not_skip_rust_drops() {
        struct Marker(Arc<AtomicBool>);
        impl Drop for Marker {
            fn drop(&mut self) {
                self.0.store(true, Ordering::Release);
            }
        }
        let memory = Reservation::new(4096).unwrap();
        memory.commit(0, 4096).unwrap();
        let code = code(Access::Read, true, false);
        let destroyed = code.destroyed.clone();
        let dropped = Arc::new(AtomicBool::new(false));
        let mut state = initial();
        let checkpoint = Checkpoint::new(state.clone(), DATA);
        let scope =
            unsafe { memory.temporary_protection(0, 4096, HostProtection::NoAccess) }.unwrap();
        {
            let _marker = Marker(dropped.clone());
            let sites = [code.site];
            let regions = [region(&code, &sites)];
            let (result, handled) =
                with_session(&mut state, &checkpoint, &regions, &memory, DATA, |state| {
                    probe(&code, state, memory.ptr.as_ptr())
                })
                .unwrap();
            assert_eq!(result.result, 3);
            assert_eq!(handled, 1);
            assert!(!dropped.load(Ordering::Acquire));
            assert!(!destroyed.load(Ordering::Acquire));
        }
        assert!(dropped.load(Ordering::Acquire));
        assert!(ACTIVE.with(|slot| slot.get().is_null()));
        drop(code);
        assert!(destroyed.load(Ordering::Acquire));
        drop(scope);
    }

    #[test]
    fn cross_page_sse_fault_preserves_the_writable_prefix_and_exact_operand_address() {
        let memory = Reservation::new(8192).unwrap();
        memory.commit(0, 8192).unwrap();
        unsafe { std::ptr::write_bytes(memory.ptr.as_ptr(), 0x37, 8192) };
        let code = code(Access::Write, false, true);
        let sites = [code.site];
        let regions = [region(&code, &sites)];
        let address = DATA + 4096 - 8;
        let mut state = initial();
        let checkpoint = Checkpoint::new(state.clone(), address);
        let scope =
            unsafe { memory.temporary_protection(4096, 4096, HostProtection::Read) }.unwrap();
        let (result, handled) =
            with_session(&mut state, &checkpoint, &regions, &memory, DATA, |state| {
                probe(&code, state, unsafe { memory.ptr.as_ptr().add(4096 - 8) })
            })
            .unwrap();
        assert_eq!(result.result, 4);
        assert_eq!(result.exception, 0);
        assert_eq!(handled, 1);
        assert_eq!(state.fault_addr, address);
        assert_eq!(
            unsafe { std::slice::from_raw_parts(memory.ptr.as_ptr().add(4096 - 8), 16) },
            &[0x37; 16]
        );
        drop(scope);
    }

    #[test]
    fn nested_protection_scopes_restore_each_original_page_and_failed_scope_rolls_back() {
        let memory = Reservation::new(12288).unwrap();
        memory.commit(0, 8192).unwrap();
        let read = unsafe { memory.temporary_protection(0, 4096, HostProtection::Read) }.unwrap();
        {
            let writable =
                unsafe { memory.temporary_protection(0, 8192, HostProtection::ReadWrite) }.unwrap();
            unsafe {
                *memory.ptr.as_ptr() = 0x91;
                *memory.ptr.as_ptr().add(4096) = 0x37;
            }
            drop(writable);
        }
        assert!(
            unsafe { memory.temporary_protection(0, 12288, HostProtection::NoAccess) }.is_err()
        );
        let code = code(Access::Write, false, false);
        let result = probe(&code, &mut initial(), memory.ptr.as_ptr());
        assert_eq!(result.exception, ACCESS_VIOLATION); // TLS is clear; RO restored.
        let result = probe(&code, &mut initial(), unsafe {
            memory.ptr.as_ptr().add(4096)
        });
        assert_eq!(result.exception, 0); // Neighbor's original RW protection remains.
        drop(read);
        let result = probe(&code, &mut initial(), memory.ptr.as_ptr());
        assert_eq!(result.exception, 0);
    }

    #[test]
    fn native_unwind_table_is_retired_before_executable_owner() {
        let mut code = code(Access::Read, false, false);
        let pc = code.site.host_pc;
        assert_ne!(unsafe { adv_host_unwind_lookup(pc) }, 0);
        // Keep the code mapped while inspecting removal, so parallel tests
        // cannot recycle its address and register another table at the same PC.
        code.unwind.clear();
        assert_eq!(unsafe { adv_host_unwind_lookup(pc) }, 0);
        assert!(!code.destroyed.load(Ordering::Acquire));
        drop(code);
    }

    #[test]
    fn pcm_section_protection_spans_preserve_independent_callback_alias() {
        use std::sync::atomic::{AtomicU8, Ordering};
        let memory = Reservation::new(8192).unwrap();
        let storage = crate::shared_memory::SharedAllocation::new(8192).unwrap();
        storage.map_linear(&memory, 0).unwrap();
        storage.store_u8(0, 0x91);
        storage.store_u8(4096, 0x37);
        let restricted =
            unsafe { memory.temporary_protection(0, 8192, HostProtection::NoAccess) }.unwrap();
        // The two guest section views can be restricted as one scope without
        // changing either independently owned callback/producer view.
        assert_eq!(storage.load_u8(0), 0x91);
        assert_eq!(storage.load_u8(4096), 0x37);
        {
            let writable =
                unsafe { memory.temporary_protection(0, 8192, HostProtection::ReadWrite) }.unwrap();
            for (offset, byte) in [(0, 0x12), (4096, 0x34)] {
                unsafe {
                    (&*memory.ptr.as_ptr().add(offset).cast::<AtomicU8>())
                        .store(byte, Ordering::Relaxed);
                }
            }
            drop(writable);
        }
        assert_eq!(storage.load_u8(0), 0x12);
        assert_eq!(storage.load_u8(4096), 0x34);
        drop(restricted);
        assert_eq!(
            unsafe { (&*memory.ptr.as_ptr().cast::<AtomicU8>()).load(Ordering::Relaxed) },
            0x12
        );
        drop(memory);
        assert_eq!(storage.load_u8(4096), 0x34);
    }

    #[test]
    fn tls_session_restores_after_nested_run_and_rust_unwind() {
        let memory = Reservation::new(4096).unwrap();
        let mut outer = initial();
        let outer_checkpoint = Checkpoint::new(outer.clone(), DATA);
        with_session(&mut outer, &outer_checkpoint, &[], &memory, DATA, |_| {
            let parent = ACTIVE.with(Cell::get);
            let mut inner = initial();
            let inner_checkpoint = Checkpoint::new(inner.clone(), DATA);
            let result = std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| {
                with_session(&mut inner, &inner_checkpoint, &[], &memory, DATA, |_| {
                    assert_ne!(ACTIVE.with(Cell::get), parent);
                    panic!("test Rust unwind");
                })
                .unwrap();
            }));
            assert!(result.is_err());
            assert_eq!(ACTIVE.with(Cell::get), parent);
            // An execute AV and a non-AV exception can never be guest memory
            // faults, even with a live session and matching checkpoint.
            assert_eq!(
                unsafe { dispatch(ACCESS_VIOLATION, 0, 0, 8, std::ptr::null_mut()) },
                0
            );
            assert_eq!(
                unsafe { dispatch(0xc0000094, 0, 0, 0, std::ptr::null_mut()) },
                0
            );
        })
        .unwrap();
        assert!(ACTIVE.with(|slot| slot.get().is_null()));
    }
