//! Direct3D 11 guest records projected from the pinned Windows metadata.
pub use adv_abi::types::{
    D3D11_BLEND_DESC, D3D11_BLEND_DESC1, D3D11_BUFFER_DESC, D3D11_DEPTH_STENCIL_DESC,
    D3D11_DEPTH_STENCIL_VIEW_DESC, D3D11_DEPTH_STENCILOP_DESC, D3D11_RASTERIZER_DESC,
    D3D11_RASTERIZER_DESC1, D3D11_RENDER_TARGET_BLEND_DESC, D3D11_RENDER_TARGET_BLEND_DESC1,
    D3D11_RENDER_TARGET_VIEW_DESC, D3D11_SAMPLER_DESC, D3D11_SHADER_RESOURCE_VIEW_DESC,
    D3D11_TEXTURE1D_DESC, D3D11_TEXTURE2D_DESC, D3D11_TEXTURE3D_DESC,
    D3D11_UNORDERED_ACCESS_VIEW_DESC, D3D11_VIEWPORT, DXGI_SAMPLE_DESC, RECT,
};

pub(super) fn limit(name: &str) -> u32 {
    adv_abi::constants::named("Windows.Win32.Graphics.Direct3D11.Apis", name)
        .expect("generated D3D11 limit") as u32
}
