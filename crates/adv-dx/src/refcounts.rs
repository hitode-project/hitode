//! Vtable AddRef/Release stay in guest code above zero. CAS loops preserve
//! concurrent x86 semantics; the original handler owns zero/overflow edges.
use adv_abi::{GuestCode, Registry};

pub(crate) fn install(registry: &mut Registry, module: &str) {
    let names: Vec<_> = registry
        .registered()
        .filter(|(m, n, _)| *m == module && (n.ends_with("::AddRef") || n.ends_with("::Release")))
        .map(|(_, n, _)| n.to_owned())
        .collect();
    for name in names {
        registry.set_guest(
            module,
            &name,
            match (
                module == "dsound.dll" || module == "quartz.dll",
                name.ends_with("::AddRef"),
            ) {
                (true, true) => &AUDIO_ADDREF,
                (true, false) => &AUDIO_RELEASE,
                (false, true) => &ADDREF,
                (false, false) => &RELEASE,
            },
        );
    }
}

