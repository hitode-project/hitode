fn permute(value: u64, width: u8, table: &[u8]) -> u64 {
    table.iter().fold(0, |result, &position| {
        (result << 1) | ((value >> (width - position)) & 1)
    })
}
impl Des {
    pub(super) fn new(key: &[u8]) -> Self {
        let key = permute(u64::from_be_bytes(key.try_into().unwrap()), 64, &PC1);
        let mut left = (key >> 28) as u32;
        let mut right = key as u32 & 0x0fffffff;
        let mut keys = [0; 16];
        for (round, key) in keys.iter_mut().enumerate() {
            let shift = if matches!(round, 0 | 1 | 8 | 15) {
                1
            } else {
                2
            };
            left = ((left << shift) | (left >> (28 - shift))) & 0x0fffffff;
            right = ((right << shift) | (right >> (28 - shift))) & 0x0fffffff;
            *key = permute((u64::from(left) << 28) | u64::from(right), 56, &PC2);
        }
        Self(keys)
    }
    pub(super) fn transform(&self, bytes: &mut [u8], decrypt: bool) {
        let input = permute(u64::from_be_bytes(bytes.try_into().unwrap()), 64, &IP);
        let mut left = (input >> 32) as u32;
        let mut right = input as u32;
        for round in 0..16 {
            let mixed = permute(u64::from(right), 32, &EXPAND)
                ^ self.0[if decrypt { 15 - round } else { round }];
            let mut sub = 0u32;
            for (index, table) in S.iter().enumerate() {
                let bits = ((mixed >> (42 - 6 * index)) & 63) as usize;
                let row = ((bits & 32) >> 4) | (bits & 1);
                sub = (sub << 4) | u32::from(table[16 * row + ((bits >> 1) & 15)]);
            }
            (left, right) = (right, left ^ permute(u64::from(sub), 32, &P) as u32);
        }
        bytes.copy_from_slice(
            &permute((u64::from(right) << 32) | u64::from(left), 64, &FP).to_be_bytes(),
        );
    }
}
