/// The routines' step from `from` towards `to`, two pixels in MMX words:
/// each byte moves by the high byte of the low word of `(to - from) * f`,
/// with `f` per pixel.
#[cfg(target_arch = "aarch64")]
fn lerp(from: u64, to: u64, f: [u16; 2]) -> u64 {
    use std::arch::aarch64::*;
    // SAFETY: every aarch64 target has NEON; nothing touches memory.
    unsafe {
        let (from, to) = (vmovl_u8(vcreate_u8(from)), vmovl_u8(vcreate_u8(to)));
        let f = vcombine_u16(vdup_n_u16(f[0]), vdup_n_u16(f[1]));
        let step = vshrq_n_u16::<8>(vmulq_u16(vsubq_u16(to, from), f));
        vget_lane_u64::<0>(vreinterpret_u64_u8(vmovn_u16(vaddq_u16(from, step))))
    }
}
#[cfg(any(test, not(target_arch = "aarch64")))]
fn lerp_scalar(from: u64, to: u64, f: [u16; 2]) -> u64 {
    let (from, to) = (from.to_le_bytes(), to.to_le_bytes());
    u64::from_le_bytes(std::array::from_fn(|i| {
        let (from, to) = (u16::from(from[i]), u16::from(to[i]));
        from.wrapping_add(to.wrapping_sub(from).wrapping_mul(f[i / 4]) >> 8) as u8
    }))
}

/// The Photoshop-style step, two pixels in MMX words: each byte moves by
/// `(to - from) * f` shifted arithmetically by 7, then saturates.
#[cfg(target_arch = "aarch64")]
fn ps_lerp(from: u64, to: u64, f: [u16; 2]) -> u64 {
    use std::arch::aarch64::*;
    // SAFETY: every aarch64 target has NEON; nothing touches memory.
    unsafe {
        let from = vreinterpretq_s16_u16(vmovl_u8(vcreate_u8(from)));
        let to = vreinterpretq_s16_u16(vmovl_u8(vcreate_u8(to)));
        let f = vreinterpretq_s16_u16(vcombine_u16(vdup_n_u16(f[0]), vdup_n_u16(f[1])));
        let step = vshrq_n_s16::<7>(vmulq_s16(vsubq_s16(to, from), f));
        vget_lane_u64::<0>(vreinterpret_u64_u8(vqmovun_s16(vaddq_s16(from, step))))
    }
}
#[cfg(any(test, not(target_arch = "aarch64")))]
fn ps_lerp_scalar(from: u64, to: u64, f: [u16; 2]) -> u64 {
    let (from, to) = (from.to_le_bytes(), to.to_le_bytes());
    u64::from_le_bytes(std::array::from_fn(|i| {
        let (from, to) = (i16::from(from[i]), i16::from(to[i]));
        let step = to.wrapping_sub(from).wrapping_mul(f[i / 4] as i16) >> 7;
        from.wrapping_add(step).clamp(0, 0xff) as u8
    }))
}

