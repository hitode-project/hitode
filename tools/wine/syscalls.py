#!/usr/bin/env python3
"""Generate the table of the system calls Wine's i386 ntdll.dll makes.

  python3 tools/wine/syscalls.py          # rewrite crates/adv-nt/src/syscalls.rs
  python3 tools/wine/syscalls.py --check  # exit 1 if the file is out of date

The numbers come from ALL_SYSCALLS32 in the vendored dlls/ntdll/ntsyscalls.h,
the table Wine's build numbers the ntdll.dll system call stubs by.
"""
from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
TABLE = ROOT / "vendor/wine/dlls/ntdll/ntsyscalls.h"
OUTPUT = ROOT / "crates/adv-nt/src/syscalls.rs"


def generate() -> str:
    text = TABLE.read_text()
    body = re.search(r"^#define ALL_SYSCALLS32 \\\n(.*?)^#", text, re.M | re.S)
    if not body:
        sys.exit(f"ALL_SYSCALLS32 not found in {TABLE.name}")
    entries = re.findall(r"SYSCALL_ENTRY(?:_\w+)?\( (0x[0-9a-f]+), (\w+), (\d+) \)", body.group(1))
    for index, (number, name, _) in enumerate(entries):
        if int(number, 16) != index:
            sys.exit(f"{name} has number {number}, expected {index:#x}")
    out = [
        "//! Wine's i386 system calls. Generated by tools/wine/syscalls.py; do not edit.",
        "",
        "/// The name of each system call and the bytes of arguments it takes, by number.",
        f"pub const SYSCALLS: [(&str, u32); {len(entries)}] = [",
    ]
    out += [f'    ("{name}", {size}),' for _, name, size in entries]
    out.append("];")
    source = "\n".join(out) + "\n"
    formatted = subprocess.run(["rustfmt", "--edition", "2024", "--emit", "stdout"],
                               input=source.encode(), capture_output=True, check=True)
    return formatted.stdout.decode()


def main(argv: list[str]) -> int:
    source = generate()
    if "--check" in argv:
        if not OUTPUT.exists() or OUTPUT.read_text() != source:
            print(f"{OUTPUT.relative_to(ROOT)} is out of date: run python3 tools/wine/syscalls.py")
            return 1
        return 0
    OUTPUT.write_text(source)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
