"""Generate the exact export exclusions for the CRT compatibility task.

Usage: python tools/abi/crt_exclusions.py [--check]
Input: data/abi/crt-exports.tsv. Output: data/abi/crt-exclusions.tsv and counts.
This is a scope manifest, not implementation coverage or an export hide list.
"""
import argparse
from collections import Counter
from pathlib import Path
import re

ABI = Path(__file__).resolve().parents[2] / "data" / "abi"
OLD_STREAM = re.compile(
    r"(?:Iostream_init|filebuf|(?:i|o)?fstream(?:base)?|(?:i|o)?strstream(?:buf)?|"
    r"(?:i|o)?stream(?:_withassign)?|ios|streambuf|stdiobuf|stdiostream)@@|"
    r"\$(?:smanip|sapp|imanip|iapp|omanip|oapp)")


def reason(module, name):
    """Classify only the task's explicit namespace/module/old-stream exclusions."""
    if module == "api-ms-win-crt-private-l1-1-0.dll":
        return "private API set"
    if "@Concurrency@@" in name:
        return "ConcRT namespace"
    if module in {"msvcrt20.dll", "msvcrt40.dll"} and OLD_STREAM.search(name):
        return "legacy iostream family"
    return None


def manifest(catalog):
    """Return sorted module/name/kind/reason rows from a names-only catalog."""
    result = []
    for row in catalog.splitlines():
        if not row or row.startswith("#"):
            continue
        module, name, kind = row.split("\t")
        excluded = reason(module, name)
        if excluded:
            result.append((module, name, kind, excluded))
    return sorted(result)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    rows = manifest((ABI / "crt-exports.tsv").read_text(encoding="utf-8"))
    output = ("# Generated by tools/abi/crt_exclusions.py; scope only, not implementation coverage.\n"
              "# module\tname\tkind\treason\n"
              + "".join("\t".join(row) + "\n" for row in rows))
    target = ABI / "crt-exclusions.tsv"
    if args.check:
        if target.read_text(encoding="utf-8") != output:
            parser.error("CRT exclusion manifest differs from its catalog")
    else:
        target.write_text(output, encoding="utf-8", newline="\n")
    for category, count in sorted(Counter(row[3] for row in rows).items()):
        print(f"{category}: {count}")
    print(f"total: {len(rows)}")


if __name__ == "__main__":
    main()
