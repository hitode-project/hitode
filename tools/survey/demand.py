"""Merge per-game `adv-run --survey` reports into data/abi/demand.tsv.

Usage: python tools/survey/demand.py <survey.json> [...]   (one report per game)
A row is one gap a static survey found (PERS-EXPORT-9, PERS-EXPORT-10) and the
number of games needing it, so compatibility work can be ranked by demand.
Output lists API names, CLSIDs and argument values only: no folder, file or
game name, address or code.
"""
import argparse
import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import coverage  # noqa: E402

KINDS = {
    "missing_modules": "module",
    "missing_imports": "import",
    "absent_loads": "load",
    "unavailable_lookups": "lookup",
    "undeclared_lookups": "undeclared",
    "missing_classes": "class",
}
DISCARDED = " (result discarded)"


def demand(reports):
    games = {}
    for report in reports:
        rows = set()
        for key, kind in KINDS.items():
            rows |= {(kind, item, "") for item in report[key]}
        for item in report["unsupported_modes"]:
            api, _, value = item.removesuffix(DISCARDED).rpartition("=")
            rows.add(("mode", api, value))
        for api, values in report["unreviewed_modes"].items():
            rows |= {("unreviewed", api, value) for value in values}
        for row in rows:
            games[row] = games.get(row, 0) + 1
    return sorted(games.items(), key=lambda entry: (entry[0][0], -entry[1], entry[0][1:]))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("reports", nargs="+", type=pathlib.Path)
    args = parser.parse_args()
    rows = demand(json.loads(path.read_text(encoding="utf-8")) for path in args.reports)
    text = ("# Generated by tools/survey/demand.py from local survey reports; API names only.\n"
            "# kind\titem\tvalue\tgames\n"
            + "".join(f"{kind}\t{item}\t{value}\t{count}\n" for (kind, item, value), count in rows))
    (coverage.ABI / "demand.tsv").write_text(text, encoding="utf-8", newline="\n")
    print(f"games={len(args.reports)} rows={len(rows)}")


if __name__ == "__main__":
    main()
