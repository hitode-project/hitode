"""Project the Windows API closure of game folders into data/abi/closure.tsv.

Usage: python tools/survey/closure.py <game-folder> [...]   (needs pefile)
Input: every 32-bit PE under each folder, skipping installers, uninstallers and
patchers by path. A row is a system DLL function the PEs import, or a catalogued
function name that appears as an ASCII string in a PE and is looked up at run time.
Imports between a folder's own PEs are not system calls. Output lists API names
only: no folder, file or game name, address or code.
"""
import argparse
import pathlib
import re
import sys

import pefile

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import coverage  # noqa: E402
import gap  # noqa: E402

SKIP = re.compile(r"(?i)(uninst|install|setup|patch|补丁|backup|gameux|_dl\.exe)")
STRING = re.compile(rb"[A-Za-z_][A-Za-z0-9_]{7,}")


def closure(folders, catalog):
    names = {}
    for dll, exports in catalog.items():
        if not dll.startswith(("msvc", "ucrt", "vcrun", "api-ms-win-crt")):
            for name in exports:
                names.setdefault(name, set()).add(dll)
    rows = set()
    for folder in folders:
        files = list(gap.pe_files(folder))
        own = {f.name.lower() for f in files}
        for path in files:
            if SKIP.search(str(path.relative_to(folder))):
                continue
            try:
                pe = pefile.PE(str(path), fast_load=True)
                if pe.FILE_HEADER.Machine != 0x14C:
                    continue
                rows |= {(dll, name, "import") for dll, name in gap.imports(path, own)}
            except pefile.PEFormatError:
                continue
            for text in set(STRING.findall(path.read_bytes())):
                for dll in names.get(text.decode(), ()):
                    rows.add((dll, text.decode(), "dynamic"))
    imported = {(dll, name) for dll, name, kind in rows if kind == "import"}
    return sorted(row for row in rows if row[2] == "import" or row[:2] not in imported)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("folders", nargs="+", type=pathlib.Path)
    args = parser.parse_args()
    rows = closure(args.folders, coverage.catalog())
    text = ("# Generated by tools/survey/closure.py from local game folders; API names only.\n"
            "# dll\tname\tsource (import or dynamic name string)\n"
            + "".join("\t".join(row) + "\n" for row in rows))
    (coverage.ABI / "closure.tsv").write_text(text, encoding="utf-8", newline="\n")
    print(f"rows={len(rows)} dynamic={sum(row[2] == 'dynamic' for row in rows)}")


if __name__ == "__main__":
    main()
