#!/usr/bin/env python3
"""Generate Rust token fields and DXGI layouts from the pinned DirectX-Headers archive."""
import argparse
import ast
import hashlib
import json
import math
from pathlib import Path
import re
import subprocess
import tarfile

ROOT = Path(__file__).resolve().parents[2]
DX = ROOT / "crates/adv-dx/src"
NOTICE = """// Generated by tools/gfx/generate_directx_headers.py.
// Copyright (c) Microsoft Corporation.
// SPDX-License-Identifier: MIT

"""
PREFIX = r"D3D(?:10|11|12)(?:_1)?_SB_"


def without_comments(source):
    return re.sub(r"/\*.*?\*/|//[^\n]*", "", source, flags=re.S)


def enum_values(body):
    value = -1
    values = {}
    for field in body.split(","):
        if not field.strip():
            continue
        name, equals, raw = field.partition("=")
        value = int(raw.strip(), 0) if equals else value + 1
        values[name.strip()] = value
    return values


def function_name(symbol):
    return re.sub(PREFIX, "", symbol).lower()


def argument_name(symbol):
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", symbol).lower()


def tokens(header):
    header = without_comments(header.replace("\\\n", " "))
    enums = {
        name: enum_values(body)
        for body, name in re.findall(r"typedef enum \w+\s*\{([^}]*)\}\s*(\w+)\s*;", header)
    }
    constants = {name: str(value) for values in enums.values() for name, value in values.items()}
    functions = {}
    for name, args, value in re.findall(r"^#define\s+(\w+)(\([^\n)]*\))?[ \t]+(.+)$", header, re.M):
        if not re.search(PREFIX, name):
            continue
        if args:
            functions[name] = ([arg.strip() for arg in args[1:-1].split(",")], value)
        else:
            constants[name] = value

    # The header's mask literal is two bits, but the documented field spans
    # three bits and its index representation enum uses the third bit.
    index_mask = "D3D10_SB_OPERAND_INDEX_REPRESENTATION_MASK"
    args, formula = functions[index_mask]
    width = max(enums["D3D10_SB_OPERAND_INDEX_REPRESENTATION"].values()).bit_length()
    functions[index_mask] = (args, formula.replace("0x3", hex((1 << width) - 1)))

    casts = re.compile(r"\((?:UINT|" + "|".join(enums) + r")\)")

    def expression(source, args=()):
        source = casts.sub("", source).strip()
        source = re.sub(r"\b(\d+|0x[\da-fA-F]+)[uUlL]+\b", r"\1", source)
        source = re.sub(r"\(\((\w+)\s*\)\s*!=0\)\?(\w+):0", r"(\2 if \1 != 0 else 0)", source)
        source = source.replace("SampleCount > 127 ? 127 : SampleCount", "min(SampleCount, 127)")
        source = re.sub(r"\?\s*true\s*:\s*false", "!= 0", source)
        node = ast.parse(source, mode="eval")
        for item in ast.walk(node):
            if isinstance(item, ast.Name):
                if item.id in args:
                    item.id = argument_name(item.id)
                elif item.id in functions:
                    item.id = function_name(item.id)
        result = ast.unparse(node)
        # Keep the arithmetic shift count explicit in the generated Rust.
        for item in ast.walk(node):
            if isinstance(item, ast.BinOp) and isinstance(item.op, (ast.LShift, ast.RShift)):
                amount = item.right
                if isinstance(amount, ast.BinOp) and isinstance(amount.op, (ast.Add, ast.Sub, ast.Mult)):
                    op = "<<" if isinstance(item.op, ast.LShift) else ">>"
                    text = ast.unparse(amount)
                    result = result.replace(f"{op} {text}", f"{op} ({text})")
        # C conditionals in this header are either selections used as whole
        # expressions or the clamp handled above.
        if isinstance(node.body, ast.IfExp):
            condition = ast.unparse(node.body.test)
            return f"if {condition} {{ {ast.unparse(node.body.body)} }} else {{ 0 }}"
        return result.replace("min(sample_count, 127)", "(if sample_count > 127 { 127 } else { sample_count })")

    generated = [NOTICE]
    for name, value in constants.items():
        generated.append(f"pub const {name}: u32 = {expression(value)};\n")
    for name, (args, value) in functions.items():
        parameters = ", ".join(f"{argument_name(arg)}: u32" for arg in args)
        result = "bool" if "? true" in value else "u32"
        generated.append(f"pub const fn {function_name(name)}({parameters}) -> {result} {{\n"
                         f"    {expression(value, args)}\n}}\n")
    # These declaration payloads start with an operand token; the other
    # declarations carry only literal words or encode their fields in the opcode.
    operand_declarations = {
        "RESOURCE", "CONSTANT_BUFFER", "SAMPLER", "INDEX_RANGE", "STREAM",
        "INPUT", "INPUT_SGV", "INPUT_SIV", "INPUT_PS", "INPUT_PS_SGV", "INPUT_PS_SIV",
        "OUTPUT", "OUTPUT_SGV", "OUTPUT_SIV", "UNORDERED_ACCESS_VIEW_TYPED",
        "UNORDERED_ACCESS_VIEW_RAW", "UNORDERED_ACCESS_VIEW_STRUCTURED", "RESOURCE_RAW",
        "RESOURCE_STRUCTURED", "THREAD_GROUP_SHARED_MEMORY_RAW", "THREAD_GROUP_SHARED_MEMORY_STRUCTURED",
    }
    declarations = {name: name.split("_DCL_")[1] in operand_declarations
                    for name in enums["D3D10_SB_OPCODE_TYPE"] if "_DCL_" in name}
    generated.append("pub const fn declaration_has_operand(opcode: u32) -> Option<bool> {\n"
                     "    match opcode {\n")
    for has_operand in (True, False):
        names = [name for name, selected in declarations.items() if selected == has_operand]
        generated.append(f"        {' | '.join(names)} => Some({str(has_operand).lower()}),\n")
    generated.append("        _ => None,\n    }\n}\n")
    return "".join(generated)


def layouts(table, header):
    enum_body = re.search(r"enum DXGI_FORMAT\s*\{([^}]*)\}", without_comments(header))[1]
    numbers = enum_values(enum_body)
    table = without_comments(table)
    block_test = re.search(r"::IsBlockCompressFormat\(DXGI_FORMAT Format\)\s*\{([^}]+)\}", table)[1]
    block_ranges = [
        range(numbers[first], numbers[last] + 1)
        for first, last in re.findall(r"Format >= (DXGI_FORMAT_\w+) && Format <= (DXGI_FORMAT_\w+)", block_test)
    ]
    cast_sets = {}
    for name, body in re.findall(r"constexpr DXGI_FORMAT (D3DFCS_\w+)\[\]\s*=\s*\{([^}]+)\};", table):
        formats = re.findall(r"\bDXGI_FORMAT_\w+\b", body)
        cast_sets[name] = [numbers[format_] for format_ in formats[:-1]]
    body = re.search(r"::s_FormatDetail\[\]\s*=\s*\{(.*?)\n\};", table, re.S)[1]
    records = []
    for row in body.splitlines():
        row = row.strip()
        if not row:
            continue
        row = re.sub(r"DXGI_FORMAT\(([^)]+)\)", r"\1", row)
        fields = re.split(r",\s*(?![^{}]*\})", row[1:row.rindex("}")].strip().rstrip(","))
        (name, parent, cast, bits, unit, srgb, width, height, depth, layout, level,
         *properties, _dx9_vertex, _dx9_texture, _float_norm, planar, yuv, dependent, internal) = map(str.strip, fields)
        if internal == "TRUE":
            continue
        channels = properties[:4]
        interpretations = properties[4:]
        records.append((numbers[name], name, numbers[parent], cast, bits[1:-1], unit,
                        [width, height, depth], layout.removeprefix("D3DFL_"),
                        level.removeprefix("D3DFTL_"), channels, interpretations,
                        srgb, planar, yuv, dependent))
    generated = [NOTICE]
    for typename, values in (
        ("Layout", {record[7] for record in records}),
        ("TypeLevel", {record[8] for record in records}),
        ("Channel", {item for record in records for item in record[9]}),
        ("Interpretation", {item for record in records for item in record[10]}),
    ):
        generated.append("#[derive(Clone, Copy, Debug, PartialEq, Eq)]\n"
                         f"pub enum {typename} {{\n"
                         + "".join(f"    {variant(value)},\n" for value in sorted(values)) + "}\n")
    generated.append("""
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct FormatLayout {
    pub format: u32,
    pub name: &'static str,
    pub parent: u32,
    pub cast_family: &'static [u32],
    pub component_bits: [u8; 4],
    /// Bits per pixel, or bits per block for block compression.
    pub unit_bits: u16,
    /// Required alignment of the texture dimensions, including compressed blocks.
    pub alignment: [u8; 3],
    /// Bytes per aligned unit. For planar formats this describes the first plane.
    pub aligned_unit_bytes: u16,
    pub layout: Layout,
    pub type_level: TypeLevel,
    pub channels: [Channel; 4],
    pub interpretations: [Interpretation; 4],
    pub srgb: bool,
    pub planar: bool,
    pub yuv: bool,
    /// Casts that depend on a plane or resource description use the default set here.
    pub dependent_casts: bool,
}

pub fn format_layout(format: u32) -> Option<&'static FormatLayout> {
    FORMATS.binary_search_by_key(&format, |row| row.format).ok().map(|index| &FORMATS[index])
}
""")
    for key in dict.fromkeys(record[3] for record in records):
        generated.append(f"const {key}: &[u32] = &{cast_sets[key]};\n")
    generated.append("pub const FORMATS: &[FormatLayout] = &[\n")
    for (value, name, parent, cast, bits, unit, alignment, layout, level, channels,
         interpretations, srgb, planar, yuv, dependent) in sorted(records):
        block_compressed = any(value in formats for formats in block_ranges)
        aligned_bits = int(unit) * (1 if block_compressed else math.prod(map(int, alignment)))
        generated.append(f"""FormatLayout {{
    format: {value}, name: "{name}", parent: {parent}, cast_family: {cast},
    component_bits: [{bits}], unit_bits: {unit}, alignment: [{", ".join(alignment)}],
    aligned_unit_bytes: {aligned_bits // 8},
    layout: Layout::{variant(layout)}, type_level: TypeLevel::{variant(level)},
    channels: [{", ".join("Channel::" + variant(channel) for channel in channels)}],
    interpretations: [{", ".join("Interpretation::" + variant(kind) for kind in interpretations)}],
    srgb: {srgb.lower()}, planar: {planar.lower()}, yuv: {yuv.lower()}, dependent_casts: {dependent.lower()},
}},\n""")
    generated.append("];\n")
    return "".join(generated)


def variant(symbol):
    return "".join(word.title() for word in symbol.strip("_").split("_"))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("archive", type=Path, help="pinned DirectX-Headers source tarball")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source = json.loads((ROOT / "data/gfx/directx-headers-source.json").read_text())
    if hashlib.sha256(args.archive.read_bytes()).hexdigest() != source["archive_sha256"]:
        raise SystemExit("DirectX-Headers archive hash mismatch")
    with tarfile.open(args.archive) as archive:
        def read(path):
            root = "DirectX-Headers-" + source["version"].removeprefix("v")
            return archive.extractfile(f"{root}/{path}").read().decode()
        outputs = {
            DX / "shader/dxbc/fields.rs": tokens(read("include/directx/D3D12TokenizedProgramFormat.hpp")),
            DX / "dxgi/formats.rs": layouts(read("src/d3dx12_property_format_table.cpp"),
                                          read("include/directx/dxgiformat.h")),
        }
    for path, contents in outputs.items():
        formatted = subprocess.check_output(["rustfmt", "--edition", "2024", "--emit", "stdout"], input=contents, text=True)
        if args.check:
            if path.read_text() != formatted:
                raise SystemExit(f"Stale {path.relative_to(ROOT)}")
        else:
            path.write_text(formatted)


if __name__ == "__main__":
    main()
