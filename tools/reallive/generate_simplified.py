"""Regenerate the Japanese-to-Simplified-Chinese character table.

Usage: python3 tools/reallive/generate_simplified.py
Input: vendor/opencc dictionaries. Only entries with a single candidate count.
A traditional character takes its simplified form (TSCharacters). A Japanese
form outside GB2312 first takes its traditional form (JPShinjitaiCharacters).
Characters GB2312 already holds stay, so 予 or 台 never become 豫 or 臺. The
table keeps the Shift_JIS characters whose result differs and exists in GBK.
Output: crates/adv-runtime/src/reallive/simplified.rs.
"""
import pathlib
import subprocess

BASE = pathlib.Path(__file__).resolve().parents[2]
SOURCES = BASE / 'vendor/opencc'
OUTPUT = BASE / 'crates/adv-runtime/src/reallive/simplified.rs'


def dictionary(name):
    table = {}
    for line in (SOURCES / name).read_text(encoding='utf-8').splitlines():
        if line.startswith('#') or '\t' not in line:
            continue
        key, values = line.split('\t')
        if ' ' not in values:
            table[key] = values
    return table


def in_gb2312(char):
    try:
        char.encode('gb2312')
        return True
    except UnicodeEncodeError:
        return False


def pairs():
    traditional = dictionary('JPShinjitaiCharacters.txt')
    simplified = dictionary('TSCharacters.txt')
    found = {}
    for lead in [*range(0x81, 0xA0), *range(0xE0, 0xFD)]:
        for trail in range(0x40, 0xFD):
            try:
                char = bytes([lead, trail]).decode('cp932')
            except UnicodeDecodeError:
                continue
            target = simplified.get(char)
            if target is None and not in_gb2312(char):
                target = traditional.get(char, char)
                target = simplified.get(target, target)
            if target is None or len(target) != 1 or target == char or ord(char) > 0xFFFF or ord(target) > 0xFFFF:
                continue
            try:
                target.encode('gbk')
            except UnicodeEncodeError:
                continue
            found[ord(char)] = ord(target)
    return sorted(found.items())


def main():
    rows = pairs()
    lines = [
        '// Generated by tools/reallive/generate_simplified.py; do not edit by hand.',
        '// Source: OpenCC dictionaries in vendor/opencc, Apache-2.0.',
        '// Rows: Shift_JIS character, its Simplified Chinese form in GBK; sorted.',
        'pub(super) const SIMPLIFIED: &[(u16, u16)] = &[',
    ]
    for start in range(0, len(rows), 6):
        lines.append('    ' + ' '.join(f'(0x{a:04x}, 0x{b:04x}),' for a, b in rows[start:start + 6]))
    lines.append('];')
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text('\n'.join(lines) + '\n')
    subprocess.run(['rustfmt', '--edition', '2024', str(OUTPUT)], check=True)
    print(f'{len(rows)} rows -> {OUTPUT.relative_to(BASE)}')


if __name__ == '__main__':
    main()
